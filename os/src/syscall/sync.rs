/// semaphore create syscall
pub fn sys_semaphore_create(res_count: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_semaphore_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let process = current_process();
    let pid = process.getpid();
    let mut process_inner = process.inner_exclusive_access();
    let sem = Arc::new(Semaphore::new(res_count));
    let id = if let Some(id) = process_inner
        .semaphore_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        process_inner.semaphore_list[id] = Some(Arc::clone(&sem));
        id
    } else {
        process_inner.semaphore_list.push(Some(Arc::clone(&sem)));
        process_inner.semaphore_list.len() - 1
    };
    drop(process_inner);
    sem.set_ridx(id);
    with_resource_manager(|rm| rm.add_resource(pid, true, id, res_count));
    id as isize
}
