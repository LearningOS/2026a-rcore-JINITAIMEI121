/// condvar create syscall
pub fn sys_condvar_create() -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_condvar_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let process = current_process();
    let pid = process.getpid();
    let mut process_inner = process.inner_exclusive_access();
    let condvar = Arc::new(Condvar::new());
    let id = if let Some(id) = process_inner
        .condvar_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        process_inner.condvar_list[id] = Some(Arc::clone(&condvar));
        id
    } else {
        process_inner.condvar_list.push(Some(Arc::clone(&condvar)));
        process_inner.condvar_list.len() - 1
    };
    drop(process_inner);
    condvar.set_ridx(id);
    // A condvar shares the mutex half of the graph namespace: waiting on it is
    // waiting for whoever holds/signal-s it.
    with_resource_manager(|rm| rm.add_resource(pid, false, id, 1));
    id as isize
}
