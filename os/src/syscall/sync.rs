use crate::sync::{with_resource_manager, Condvar, Mutex, MutexBlocking, MutexSpin, Semaphore, DEADLOCK};
use crate::task::{block_current_and_run_next, current_process, current_task};
use crate::timer::{add_timer, get_time_ms};
use alloc::sync::Arc;
/// sleep syscall
pub fn sys_sleep(ms: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_sleep",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let expire_ms = get_time_ms() + ms;
    let task = current_task().unwrap();
    add_timer(expire_ms, task);
    block_current_and_run_next();
    0
}
/// mutex create syscall
pub fn sys_mutex_create(blocking: bool) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let process = current_process();
    let pid = process.getpid();
    let blocking_mutex: Option<Arc<MutexBlocking>> = if blocking {
        Some(Arc::new(MutexBlocking::new()))
    } else {
        None
    };
    // A spin mutex never enters the wait-for graph: it only yields the CPU, so
    // it cannot be part of a cycle.
    let mutex: Option<Arc<dyn Mutex>> = match &blocking_mutex {
        Some(m) => Some(m.clone()),
        None => Some(Arc::new(MutexSpin::new())),
    };
    let mut process_inner = process.inner_exclusive_access();
    let id = match process_inner
        .mutex_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        Some(id) => {
            process_inner.mutex_list[id] = mutex;
            id
        }
        None => {
            process_inner.mutex_list.push(mutex);
            process_inner.mutex_list.len() - 1
        }
    };
    drop(process_inner);
    if let Some(mutex) = blocking_mutex {
        mutex.set_ridx(id);
        with_resource_manager(|rm| rm.add_resource(pid, false, id, 1));
    }
    id as isize
}
/// mutex lock syscall
pub fn sys_mutex_lock(mutex_id: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_lock",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let process = current_process();
    let process_inner = process.inner_exclusive_access();
    let mutex = Arc::clone(process_inner.mutex_list[mutex_id].as_ref().unwrap());
    drop(process_inner);
    drop(process);
    // -0xdead when taking this mutex would close a cycle in the wait-for graph
    match mutex.try_lock_or_block() {
        Ok(()) => 0,
        Err(()) => DEADLOCK,
    }
}
